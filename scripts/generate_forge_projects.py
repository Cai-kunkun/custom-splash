FORGE_PLATFORM = r"""package dev.arrbrants.customsplash;

import net.minecraftforge.fml.ModList;
import net.minecraftforge.fml.loading.FMLPaths;

import java.nio.file.Path;

/**
 * Forge implementation of {@link SplashPlatform}, installed by
 * {@link CustomSplash} at mod construction time.
 */
public final class ForgeSplashPlatform implements SplashPlatform {

	private ForgeSplashPlatform() {
	}

	public static void install() {
		SplashPlatform.install(new ForgeSplashPlatform());
	}

	@Override
	public Path getConfigDir() {
		return FMLPaths.CONFIGDIR.get();
	}

	@Override
	public Path getGameDir() {
		return FMLPaths.GAMEDIR.get();
	}

	@Override
	public boolean isModLoaded(String modId) {
		return ModList.get().isLoaded(modId);
	}

	@Override
	public int loadedModCount() {
		return ModList.get().getMods().size();
	}
}
"""

FORGE_INITIALIZER = r"""package dev.arrbrants.customsplash;

import net.minecraftforge.fml.common.Mod;
import net.minecraftforge.fml.event.lifecycle.FMLCommonSetupEvent;
import net.minecraftforge.fml.javafmlmod.FMLJavaModLoadingContext;
import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;

@Mod(CustomSplash.MOD_ID)
public class CustomSplash {
	public static final String MOD_ID = "custom-splash";
	public static final Logger LOGGER = LogManager.getLogger(MOD_ID);

	public CustomSplash() {
		ForgeSplashPlatform.install();
		FMLJavaModLoadingContext.get().getModEventBus().addListener(this::onCommonSetup);
		LOGGER.info("Custom Splash has initialized");
	}

	private void onCommonSetup(FMLCommonSetupEvent event) {
		SplashRegistry.reload();
	}
}
"""


def main() -> None:
	versions = FORGE_VERSIONS_FILE.read_text().splitlines()
	fabric_versions = (ROOT / "supported-versions.txt").read_text().splitlines()
	for minecraft in versions:
		if minecraft not in FORGE_SPECS:
			raise SystemExit(f"no Forge spec for {minecraft}")
		if minecraft not in fabric_versions:
			raise SystemExit(f"{minecraft} is not a Fabric version project")

		forge_version, java_version, loader_range, mc_range = FORGE_SPECS[minecraft]
		project = ROOT / "versions" / f"{minecraft}-forge"
		write(project, Path("build.gradle"),
		      BUILD_GRADLE_FG6 if is_fg6(minecraft) else BUILD_GRADLE_FG5)
		write(project, Path("settings.gradle"),
		      (SETTINGS_GRADLE_FG6 if is_fg6(minecraft) else SETTINGS_GRADLE_FG5)
		      .replace("%%MINECRAFT%%", minecraft))
		write(project, Path("gradle.properties"),
		      GRADLE_PROPERTIES
		      .replace("%%MINECRAFT%%", minecraft)
		      .replace("%%FORGE%%", forge_version)
		      .replace("%%JAVA%%", java_version))
		copy_wrapper(project, minecraft)

		for name, content in SOURCES.items():
			write(project, PACKAGE_DIR / name, content)
		write(project, PACKAGE_DIR / "ForgeSplashPlatform.java", FORGE_PLATFORM)
		write(project, PACKAGE_DIR / "CustomSplash.java", FORGE_INITIALIZER)
		write(project, PACKAGE_DIR / "mixin" / "SplashManagerMixin.java", mixin_for(minecraft))

		write(project, RESOURCES_DIR / "META-INF" / "mods.toml",
		      MODS_TOML
		      .replace("%%LOADER_RANGE%%", loader_range)
		      .replace("%%MC_RANGE%%", mc_range))
		write(project, RESOURCES_DIR / "customsplash.mixins.json",
		      MIXINS_JSON.replace("%%COMPAT%%", mixin_compatibility(minecraft)))
		print(f"updated forge {minecraft}")


if __name__ == "__main__":
	main()
