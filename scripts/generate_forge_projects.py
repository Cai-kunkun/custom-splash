#!/usr/bin/env python3
"""Generate the Forge version projects (1.16.1 - 1.20.6).

For every Minecraft version in supported-forge-versions.txt this script writes
a complete standalone ForgeGradle project under versions/<mc>-forge. It reuses
the exact same shared sources and mixins generated by
scripts/generate_common_sources.py (imported here), plus the two Forge-only
classes: the @Mod entry point and the SplashPlatform implementation. The 1.16.x
mixins are retargeted to the SRG class name because those MCPConfigs predate
official class mappings (see forge_mixin_for).

Build recipes mirror the official Forge MDK templates:
  - 1.16.1..1.19.4: ForgeGradle 5.1.+ on Gradle 7.6.4
  - 1.20.1..1.20.4: ForgeGradle 6.+ on Gradle 8.13
  - 1.20.6:         ForgeGradle 7.x on Gradle 9.6.0 (official runtime names,
                    no reobfuscation and no mixin refmap)
The ForgeGradle 5/6 projects apply MixinGradle 0.7-SNAPSHOT via the buildscript
classpath, declare the refmap and mixin config in the mixin closure and
finalize the jar with reobfJar, exactly like the MDK's mixin workflow.

Run from the repository root: python3 scripts/generate_forge_projects.py
"""

