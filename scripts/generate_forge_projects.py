def is_fg6(minecraft: str) -> bool:
    major, minor = (int(p) for p in minecraft.split(".")[:2])
    return (major, minor) >= (1, 20)


def mixin_compatibility(minecraft: str) -> str:
    if minecraft == "1.16.5":
        return "JAVA_8"
    if minecraft == "1.17.1":
        return "JAVA_16"
    return "JAVA_17"


def gradle_distribution_url(minecraft: str) -> str:
    version = "8.13" if is_fg6(minecraft) else "7.6.4"
    return "https\\://services.gradle.org/distributions/gradle-%s-bin.zip" % version


def write(project: Path, relative: Path, content: str) -> None:
    target = project / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")


def copy_wrapper(project: Path, minecraft: str) -> None:
    """Reuse the wrapper scripts and jar from the matching Fabric project."""
    source = ROOT / "versions" / minecraft
    (project / "gradle" / "wrapper").mkdir(parents=True, exist_ok=True)
    for name in ("gradlew", "gradlew.bat", "gradle/wrapper/gradle-wrapper.jar"):
        shutil.copyfile(source / name, project / name)
    (project / "gradlew").chmod(0o755)
    write(project, Path("gradle/wrapper/gradle-wrapper.properties"),
          WRAPPER_PROPERTIES.replace("%%DIST_URL%%", gradle_distribution_url(minecraft)))


BUILD_GRADLE_FG5 = r"""buildscript {
	repositories {
		maven { url = 'https://maven.minecraftforge.net/' }
		maven { url = 'https://repo.spongepowered.org/repository/maven-public/' }
		mavenCentral()
		gradlePluginPortal()
	}
	dependencies {
		classpath group: 'net.minecraftforge.gradle', name: 'ForgeGradle', version: '5.1.+', changing: true
		classpath group: 'org.spongepowered', name: 'mixingradle', version: '0.7-SNAPSHOT'
	}
}

apply plugin: 'net.minecraftforge.gradle'
apply plugin: 'org.spongepowered.mixin'
apply plugin: 'maven-publish'

def gitCommit = providers.exec {
	commandLine 'git', 'rev-parse', '--short=8', 'HEAD'
}.standardOutput.asText.getOrElse('').trim()

version = "${rootProject.mod_version}+forge-mc${minecraft_version}" + (gitCommit.isEmpty() ? '' : ".${gitCommit}")
group = rootProject.maven_group
archivesBaseName = "custom-splash-${minecraft_version}-forge"

minecraft {
	mappings channel: 'official', version: minecraft_version
}

mixin {
	add sourceSets.main, 'customsplash.refmap.json'
	config 'customsplash.mixins.json'
}

dependencies {
	minecraft "net.minecraftforge:forge:${minecraft_version}-${forge_version}"
	implementation 'org.spongepowered:mixin:0.8.5'
	annotationProcessor 'org.spongepowered:mixin:0.8.5:processor'
}

processResources {
	inputs.property 'version', project.version
	inputs.property 'minecraft_version', minecraft_version
	inputs.property 'forge_version', forge_version
	filesMatching('META-INF/mods.toml') {
		expand version: project.version, minecraft_version: minecraft_version, forge_version: forge_version
	}
}

tasks.withType(JavaCompile).configureEach {
	options.encoding = 'UTF-8'
	options.release = Integer.parseInt(java_version)
}

jar {
	finalizedBy 'reobfJar'
	manifest {
		attributes 'MixinConfigs': 'customsplash.mixins.json'
	}
	from(rootProject.file('LICENSE')) {
		rename { "${it}_${archivesBaseName}" }
	}
}
"""

