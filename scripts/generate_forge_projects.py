def is_fg7(minecraft: str) -> bool:
    """1.20.5+ switched to official runtime names and ForgeGradle 7."""
    major, minor, *patch = (int(p) for p in minecraft.split("."))
    if (major, minor) != (1, 20):
        return (major, minor) > (1, 20)
    return bool(patch) and patch[0] >= 5


def is_fg6(minecraft: str) -> bool:
    major, minor = (int(p) for p in minecraft.split(".")[:2])
    return (major, minor) >= (1, 20)


def mixin_compatibility(minecraft: str) -> str:
    # Forge 1.20.6 bundles Mixin 0.8.5, whose CompatibilityLevel enum stops at
    # JAVA_17, so naming a newer level aborts startup with a MixinInitialisationError.
    # NeoForge ships a newer Mixin and is free to name JAVA_21 and up.
    if minecraft.startswith("1.16"):
        return "JAVA_8"
    if minecraft == "1.17.1":
        return "JAVA_16"
    return "JAVA_17"


def gradle_distribution_url(minecraft: str) -> str:
    if is_fg7(minecraft):
        version = "9.6.0"
    elif is_fg6(minecraft):
        version = "8.13"
    else:
        version = "7.6.4"
    return "https\\://services.gradle.org/distributions/gradle-%s-bin.zip" % version


def forge_mixin_for(minecraft: str) -> str:
    """The shared mixin, adjusted for Forge's mapping behaviour.

    The 1.16.x MCPConfigs are the only supported ones not marked official:
    ForgeGradle keeps the SRG class names there (only fields and methods are
    renamed to the Mojang names), so those mixins have to target
    ``net.minecraft.client.util.Splashes`` instead of the official
    ``net.minecraft.client.resources.SplashManager``.
    """
    source = mixin_for(minecraft)
    if minecraft.startswith("1.16"):
        source = source.replace(
            "import net.minecraft.client.resources.SplashManager;",
            "import net.minecraft.client.util.Splashes;",
        ).replace(
            "@Mixin(SplashManager.class)",
            "@Mixin(Splashes.class)",
        )
    return source


